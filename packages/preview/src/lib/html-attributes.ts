/** Whether `name` is a native HTML attribute a passthrough root forwards. */
export function isHtmlAttribute(name: string): boolean {
  return HTML_ATTRIBUTES.has(name) || /^(aria|data)-[a-z0-9-]+$/.test(name);
}
